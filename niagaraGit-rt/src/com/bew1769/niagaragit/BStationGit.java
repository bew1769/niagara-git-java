  private void submit(final String name, final Job job) {
    if (executor == null) {
      setStatus(name + " refused: component is not running");
      return;
    }
    if (!busy.compareAndSet(false, true)) {
      setStatus(name + " refused: another operation is running");
      return;
    }
    final StationGit.Settings settings;
    try {
      settings = settings();
    } catch (RuntimeException e) {
      busy.set(false);
      finish(name, "failed: " + describe(e), null);
      return;
    }
    setStatus(name + " running");
    executor.execute(new Runnable() {
      @Override
      public void run() {
        try {
          bogNote = "";
          StationGit.Outcome o = job.run(settings);
          finish(name, o.message + bogNote, o.head);
        } catch (Throwable t) {
          LOG.log(Level.WARNING, "niagaraGit " + name + " failed", t);
          finish(name, "failed: " + describe(t), null);
        } finally {
          busy.set(false);
        }
      }
    });
  }

